const corpusLicense = "MIT (generated by this repository)"
const rssNote = "Go runtime MemStats.Sys at suite end, not OS RSS"

var (
	panicsObserved   int
	timeoutsObserved int
)

type fixture struct {
	ID        string
	Filename  string
	Generator string
	Suites    []string
	Data      []byte
}

type manifestEntry struct {
	ID        string   `json:"id"`
	Filename  string   `json:"filename"`
	Generator string   `json:"generator"`
	License   string   `json:"license"`
	Sha256    string   `json:"sha256"`
	Suites    []string `json:"suites"`
}

func shaHex(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

func repoRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		return ""
	}
	for i := 0; i < 10; i++ {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	return ""
}

func cmdOutput(d time.Duration, name string, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), d)
	defer cancel()
	cmd := exec.CommandContext(ctx, name, args...)
	var out bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &out
	if err := cmd.Run(); err != nil {
		return "", err
	}
	return strings.TrimSpace(out.String()), nil
}

func sysRSSkb() int64 {
	var m runtime.MemStats
	runtime.ReadMemStats(&m)
	return int64(m.Sys / 1024)
}

// guarded runs fn, counting recovered panics and >30s overruns as timeouts.
func guarded(fn func() map[string]any) (res map[string]any) {
	start := time.Now()
	defer func() {
		if r := recover(); r != nil {
			panicsObserved++
			res = map[string]any{"error": fmt.Sprintf("panic: %v", r)}
		}
		if time.Since(start) > 30*time.Second {
			timeoutsObserved++
		}
	}()
	return fn()
}

func zipParts(data []byte) (map[string][]byte, error) {
	zr, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return nil, err
	}
	parts := make(map[string][]byte, len(zr.File))
	for _, f := range zr.File {
		if f.FileInfo().IsDir() {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return nil, err
		}
		b, err := io.ReadAll(rc)
		rc.Close()
		if err != nil {
			return nil, err
		}
		parts[f.Name] = b
	}
	return parts, nil
}

// unrequestedRate compares decompressed entries, ignoring targeted parts.
func unrequestedRate(before, after map[string][]byte, targeted map[string]bool) ([]string, float64, int) {
	total := len(before)
	var changed []string
	for name, b := range before {
		if targeted[name] {
			continue
		}
		a, ok := after[name]
		if !ok || !bytes.Equal(a, b) {
			changed = append(changed, name)
		}
	}
	for name := range after {
		if targeted[name] {
			continue
		}
		if _, ok := before[name]; !ok {
			changed = append(changed, name)
		}
	}
	sort.Strings(changed)
	rate := 0.0
	if total > 0 {
		rate = float64(len(changed)) / float64(total)
	}
	return changed, rate, total
}

func pctNearestRank(ms []float64, p float64) float64 {
	if len(ms) == 0 {
		return 0
	}
	s := append([]float64(nil), ms...)
	sort.Float64s(s)
	rank := int(math.Ceil(p/100*float64(len(s)))) - 1
	if rank < 0 {
		rank = 0
	}
	if rank >= len(s) {
		rank = len(s) - 1
	}
	return math.Round(s[rank]*1000) / 1000
}

// injectCustomXML adds an unknown part plus its content-type override.
func injectCustomXML(base []byte) ([]byte, error) {
	zr, err := zip.NewReader(bytes.NewReader(base), int64(len(base)))
	if err != nil {
		return nil, err
	}
	parts := map[string][]byte{}
	var order []string
	for _, f := range zr.File {
		if f.FileInfo().IsDir() {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return nil, err
		}
		b, err := io.ReadAll(rc)
		rc.Close()
		if err != nil {
			return nil, err
		}
		parts[f.Name] = b
		order = append(order, f.Name)
	}
	ct := string(parts["[Content_Types].xml"])
	extra := `  <Override PartName="/customXml/item1.xml" ContentType="application/xml"/>` + "\n"
	ct = strings.Replace(ct, "</Types>", extra+"</Types>", 1)
	parts["[Content_Types].xml"] = []byte(ct)
	parts["customXml/item1.xml"] = []byte(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?><item><val>bench-unknown-object</val></item>`)
	order = append(order, "customXml/item1.xml")
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	for _, name := range order {
		f, err := w.Create(name)
		if err != nil {
			return nil, err
		}
		if _, err := f.Write(parts[name]); err != nil {
			return nil, err
		}
	}
	if err := w.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func buildCorpus() ([]fixture, error) {
	minimal, err := ooxml.CreateDOCXFromParagraphs([]ooxml.DocxParagraph{{Text: "Benchmark minimal", Size: 24}})
	if err != nil {
		return nil, err
	}
	table, err := ooxml.CreateCorporateReport("Benchmark Report",
		ooxml.CorporateOptions{Subtitle: "Phase F", Date: "2026-01-01"},
		[]ooxml.CorporateSection{{
			Heading: "Results",
			Level:   1,
			Body:    []string{"First paragraph.", "Second paragraph."},
			Table:   &ooxml.TableData{Headers: []string{"Name", "Value"}, Rows: [][]string{{"a", "1"}, {"b", "2"}}},
		}})
	if err != nil {
		return nil, err
	}
	customBase, err := ooxml.CreateDOCX("Custom XML host")
	if err != nil {
		return nil, err
	}
	custom, err := injectCustomXML(customBase)
	if err != nil {
		return nil, err
	}
	xlsx, err := ooxml.CreateXLSXFromData("Bench",
		[]string{"Item", "Qty", "Price"},
		[][]string{{"Apple", "3", "1.50"}, {"Banana", "2", "0.75"}, {"Total", "", "=SUM(C2:C3)"}})
	if err != nil {
		return nil, err
	}
	pptx, err := ooxml.CreatePPTXFromSlides([]ooxml.SlideData{
		{Title: "Slide one", Content: "First"},
		{Title: "Slide two", Content: "Second"},
		{Title: "Slide three", Content: "Third"},
	})
	if err != nil {
		return nil, err
	}
	return []fixture{
		{ID: "minimal_docx", Filename: "minimal.docx", Generator: "ooxml.CreateDOCXFromParagraphs", Suites: []string{"validation", "noop_preservation"}, Data: minimal},
		{ID: "docx_table_headings", Filename: "table.docx", Generator: "ooxml.CreateCorporateReport", Suites: []string{"validation", "noop_preservation", "targeted_change"}, Data: table},
		{ID: "docx_customxml", Filename: "customxml.docx", Generator: "ooxml.CreateDOCX+customXml-inject", Suites: []string{"validation", "noop_preservation", "targeted_change"}, Data: custom},
		{ID: "xlsx_data_formula", Filename: "data.xlsx", Generator: "ooxml.CreateXLSXFromData", Suites: []string{"validation", "noop_preservation", "targeted_change"}, Data: xlsx},
		{ID: "pptx_3slides", Filename: "slides.pptx", Generator: "ooxml.CreatePPTXFromSlides", Suites: []string{"validation"}, Data: pptx},
	}, nil
}

func fixtureByID(fx []fixture, id string) *fixture {
	for i := range fx {
		if fx[i].ID == id {
			return &fx[i]
		}
	}
	return nil
}

func validateOne(v *validator.Validator, store storage.Store, f *fixture) (int, error) {
	doc, err := store.Create(f.Filename, f.Data)
	if err != nil {
		return 0, err
	}
	res, err := v.Validate(doc.ID)
	if err != nil {
		return 0, err
	}
	n := 0
	for _, c := range res.Checks {
		if c.Status == "fail" {
			n++
		}
	}
	return n, nil
}

func main() {
	outDir := flag.String("out", "benchmark/results", "output directory for results")
	iters := flag.Int("iters", 20, "latency iterations per operation")
	wantJSON := flag.Bool("json", true, "write the JSON result file")
	flag.Parse()
	path, err := runBench(*outDir, *iters, *wantJSON)
	if err != nil {
		fmt.Fprintf(os.Stderr, "bench: %v\n", err)
		os.Exit(1)
	}
	if path != "" {
		fmt.Printf("result: %s\n", path)
	}
}

func runBench(outDir string, iters int, wantJSON bool) (string, error) {
	if iters < 1 {
		iters = 1
	}
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return "", err
	}
	commit := "unknown"
	if c, err := cmdOutput(10*time.Second, "git", "rev-parse", "--short", "HEAD"); err == nil && c != "" {
		commit = strings.TrimSpace(c)
	}
	now := time.Now().UTC()
	goVer := runtime.Version()
	pyVer, pyErr := cmdOutput(10*time.Second, "python3", "--version")
	ooVer, ooErr := cmdOutput(10*time.Second, "/opt/onlyoffice/desktopeditors/DesktopEditors", "--version")
	bldVer := ""
	bldErr := fmt.Errorf("unavailable")
	if b := builder.Detect(""); b.Available() {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		if v, err := b.Version(ctx); err == nil {
			bldVer, bldErr = v, nil
		} else {
			bldErr = err
		}
	}
	cpuModel := runtime.GOARCH
	if b, err := os.ReadFile("/proc/cpuinfo"); err == nil {
		for _, line := range strings.Split(string(b), "\n") {
			if strings.HasPrefix(line, "model name") {
				if i := strings.Index(line, ":"); i >= 0 {
					cpuModel = strings.TrimSpace(line[i+1:])
					break
				}
			}
		}
	}
	totalRAM := "unknown"
	if b, err := os.ReadFile("/proc/meminfo"); err == nil {
		for _, line := range strings.Split(string(b), "\n") {
			if strings.HasPrefix(line, "MemTotal:") {
				totalRAM = strings.TrimSpace(strings.TrimPrefix(line, "MemTotal:"))
				break
			}
		}
	}

	tmpDir, err := os.MkdirTemp("", "bench-corpus-*")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(tmpDir)

	fx, err := buildCorpus()
	if err != nil {
		return "", err
	}
	manifest := make([]manifestEntry, 0, len(fx))
	for _, f := range fx {
		if err := os.WriteFile(filepath.Join(tmpDir, f.Filename), f.Data, 0644); err != nil {
			return "", err
		}
		manifest = append(manifest, manifestEntry{
			ID: f.ID, Filename: f.Filename, Generator: f.Generator,
			License: corpusLicense, Sha256: shaHex(f.Data), Suites: f.Suites,
		})
	}
	// Self-verify: re-read from disk and compare with the manifest hashes.
	manifestOK := true
	manifestErr := ""
	for i, f := range fx {
		b, err := os.ReadFile(filepath.Join(tmpDir, f.Filename))
		if err != nil || shaHex(b) != manifest[i].Sha256 {
			manifestOK = false
			manifestErr = "manifest hash mismatch for " + f.ID
			if err != nil {
				manifestErr = "re-read failed for " + f.ID + ": " + err.Error()
			}
			break
		}
	}
	manifestJSON, _ := json.MarshalIndent(manifest, "", "  ")
	_ = os.WriteFile(filepath.Join(outDir, "manifest.json"), manifestJSON, 0644)
	if root := repoRoot(); root != "" {
		corpusDir := filepath.Join(root, "benchmark", "corpus")
		if err := os.MkdirAll(corpusDir, 0755); err == nil {
			_ = os.WriteFile(filepath.Join(corpusDir, "manifest.json"), manifestJSON, 0644)
		}
	}

	storeDir, err := os.MkdirTemp("", "bench-store-*")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(storeDir)
	store, err := storage.NewLocalStore(storeDir)
	if err != nil {
		return "", err
	}
	v := validator.New(store)

	suites := map[string]any{}

	// Suite 1: validation.
	suites["validation"] = guarded(func() map[string]any {
		out := map[string]any{"error": nil, "peak_rss_kb": nil, "peak_rss_kb_note": rssNote}
		details := []any{}
		total := 0
		for i := range fx {
			n, err := validateOne(v, store, &fx[i])
			if err != nil {
				return map[string]any{"error": err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
			}
			total += n
			details = append(details, map[string]any{
				"id": fFilename(fx[i]), "validation_errors": n,
				"open_without_repair": n == 0,
				"samples":             1,
			})
		}
		out["fixtures"] = details
		out["samples"] = len(fx)
		out["validation_errors"] = total
		out["notes"] = "open_without_repair is a structural proxy from the validator, not a real office open"
		out["peak_rss_kb"] = sysRSSkb()
		if !manifestOK {
			out["error"] = manifestErr
		}
		return out
	})

	// Suite 2: noop preservation.
	suites["noop_preservation"] = guarded(func() map[string]any {
		details := []any{}
		sumChanged, sumTotal := 0, 0
		for _, id := range []string{"minimal_docx", "docx_table_headings", "docx_customxml", "xlsx_data_formula"} {
			f := fixtureByID(fx, id)
			var (
				rewritten []byte
				err       error
				targeted  = map[string]bool{}
			)
			if strings.HasSuffix(f.Filename, ".xlsx") {
				targeted["xl/worksheets/sheet1.xml"] = true
				rewritten, err = ooxml.SetCellValue(f.Data, "", "B2", "3", false, "")
			} else {
				targeted["word/document.xml"] = true
				var cur string
				cur, err = ooxml.ParagraphText(f.Data, 0)
				if err == nil {
					rewritten, err = ooxml.ReplaceParagraphText(f.Data, 0, cur)
				}
			}
			if err != nil {
				return map[string]any{"error": id + ": " + err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
			}
			before, err := zipParts(f.Data)
			if err != nil {
				return map[string]any{"error": id + ": " + err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
			}
			after, err := zipParts(rewritten)
			if err != nil {
				return map[string]any{"error": id + ": " + err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
			}
			changed, rate, total := unrequestedRate(before, after, targeted)
			sumChanged += len(changed)
			sumTotal += total
			details = append(details, map[string]any{
				"id": fFilename(*f), "unrequested_changed_entries": changed,
				"unrequested_change_rate": rate, "samples": 1,
			})
		}
		details = append(details, map[string]any{
			"id": "slides.pptx", "unrequested_changed_entries": nil,
			"unrequested_change_rate": nil, "reason": "no_inplace_pptx_edit", "samples": 0,
		})
		rate := 0.0
		if sumTotal > 0 {
			rate = float64(sumChanged) / float64(sumTotal)
		}
		return map[string]any{
			"error": nil, "fixtures": details, "samples": 4,
			"unrequested_changed_entries": sumChanged,
			"unrequested_change_rate":     rate,
			"peak_rss_kb":                 sysRSSkb(), "peak_rss_kb_note": rssNote,
		}
	})

	// Suite 3: targeted change.
	suites["targeted_change"] = guarded(func() map[string]any {
		docxF := fixtureByID(fx, "docx_table_headings")
		xlsxF := fixtureByID(fx, "xlsx_data_formula")
		customF := fixtureByID(fx, "docx_customxml")
		docxOut, err := ooxml.ReplaceParagraphText(docxF.Data, 0, "BENCH TARGET TEXT")
		if err != nil {
			return map[string]any{"error": err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
		}
		got, err := ooxml.ParagraphText(docxOut, 0)
		if err != nil {
			return map[string]any{"error": err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
		}
		docxOK := got == "BENCH TARGET TEXT"
		xlsxOut, err := ooxml.SetCellValue(xlsxF.Data, "", "B2", "10", false, "")
		if err != nil {
			return map[string]any{"error": err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
		}
		afterX, err := zipParts(xlsxOut)
		if err != nil {
			return map[string]any{"error": err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
		}
		sheet := ""
		for name, b := range afterX {
			if strings.HasPrefix(name, "xl/worksheets/") {
				sheet = string(b)
			}
		}
		xlsxOK := strings.Contains(sheet, `<c r="B2"`) && strings.Contains(sheet, ">10<")
		formulaOK := strings.Contains(sheet, "SUM(C2:C3)")
		customOut, err := ooxml.ReplaceParagraphText(customF.Data, 0, "BENCH OBJECT HOST")
		if err != nil {
			return map[string]any{"error": err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
		}
		beforeC, _ := zipParts(customF.Data)
		afterC, err := zipParts(customOut)
		if err != nil {
			return map[string]any{"error": err.Error(), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote}
		}
		objectOK := bytes.Equal(beforeC["customXml/item1.xml"], afterC["customXml/item1.xml"]) && len(beforeC["customXml/item1.xml"]) > 0
		beforeD, _ := zipParts(docxF.Data)
		afterD, _ := zipParts(docxOut)
		_, r1, _ := unrequestedRate(beforeD, afterD, map[string]bool{"word/document.xml": true})
		beforeX, _ := zipParts(xlsxF.Data)
		_, r2, _ := unrequestedRate(beforeX, afterX, map[string]bool{"xl/worksheets/sheet1.xml": true})
		beforeO, _ := zipParts(customF.Data)
		_, r3, _ := unrequestedRate(beforeO, afterC, map[string]bool{"word/document.xml": true})
		taskOK := docxOK && xlsxOK
		return map[string]any{
			"error": nil, "samples": 3,
			"task_success":            taskOK,
			"task_success_checks":     map[string]any{"docx_replace_paragraph": docxOK, "xlsx_set_cell": xlsxOK},
			"formula_preserved":       formulaOK,
			"object_preserved":        objectOK,
			"unrequested_change_rate": (r1 + r2 + r3) / 3,
			"peak_rss_kb":             sysRSSkb(), "peak_rss_kb_note": rssNote,
		}
	})

	// Suite 4: conflict detection.
	suites["conflict_detection"] = guarded(func() map[string]any {
		correct := 0
		for i := 0; i < 200; i++ {
			d := fmt.Sprintf("digest-%03d", i)
			if i%2 == 0 {
				if err := operations.CheckRevision(d, d); err == nil {
					correct++
				}
			} else {
				if err := operations.CheckRevision(d, d+"-other"); err != nil {
					if _, ok := err.(*operations.ConflictError); ok {
						correct++
					}
				}
			}
		}
		return map[string]any{
			"error": nil, "samples": 200,
			"conflict_detection_accuracy": float64(correct) / 200,
			"correct":                     correct, "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote,
		}
	})

	// Suite 5: rollback.
	suites["rollback"] = guarded(func() map[string]any {
		rbOK, rbN, unkOK, unkN := 0, 0, 0, 0
		for i := 0; i < 100; i++ {
			tx := operations.NewTransaction(fmt.Sprintf("bench-tx-%d", i), "bench-doc", "bench.op", "before")
			switch i % 3 {
			case 0: // prepare -> commit -> rollback
				rbN++
				if _, err := tx.Commit("after"); err != nil {
					continue
				}
				if rc, err := tx.Rollback(); err == nil && rc.RolledBack {
					rbOK++
				}
			case 1: // prepare -> rollback
				rbN++
				if rc, err := tx.Rollback(); err == nil && rc.RolledBack {
					rbOK++
				}
			default: // prepare -> unknown
				unkN++
				if rc, err := tx.MarkUnknown("bench timeout"); err == nil && rc.UnknownOutcome {
					unkOK++
				}
			}
		}
		rbRate, unkRate := 0.0, 0.0
		if rbN > 0 {
			rbRate = float64(rbOK) / float64(rbN)
		}
		if unkN > 0 {
			unkRate = float64(unkOK) / float64(unkN)
		}
		return map[string]any{
			"error": nil, "samples": 100,
			"rollback_success_rate":         rbRate,
			"rollback_ok":                   rbOK,
			"rollback_attempts":             rbN,
			"unknown_outcome_reported_rate": unkRate,
			"unknown_ok":                    unkOK,
			"unknown_attempts":              unkN,
			"peak_rss_kb":                   sysRSSkb(), "peak_rss_kb_note": rssNote,
		}
	})

	// Suite 6: latency (uses iters runs per operation, nearest-rank).
	suites["latency"] = guarded(func() map[string]any {
		minimal := fixtureByID(fx, "minimal_docx")
		docxF := fixtureByID(fx, "docx_table_headings")
		xlsxF := fixtureByID(fx, "xlsx_data_formula")
		measure := func(n int, fn func()) map[string]any {
			ms := make([]float64, 0, n)
			for i := 0; i < n; i++ {
				t0 := time.Now()
				fn()
				ms = append(ms, float64(time.Since(t0).Microseconds())/1000)
			}
			return map[string]any{
				"p50_ms": pctNearestRank(ms, 50), "p95_ms": pctNearestRank(ms, 95),
				"p99_ms": pctNearestRank(ms, 99), "samples": n,
			}
		}
		ops := map[string]any{}
		ops["validate_docx"] = measure(iters, func() { _, _ = validateOne(v, store, minimal) })
		ops["validate_xlsx"] = measure(iters, func() { _, _ = validateOne(v, store, xlsxF) })
		ops["noop_docx"] = measure(iters, func() {
			cur, err := ooxml.ParagraphText(docxF.Data, 0)
			if err == nil {
				_, _ = ooxml.ReplaceParagraphText(docxF.Data, 0, cur)
			}
		})
		ops["noop_xlsx"] = measure(iters, func() { _, _ = ooxml.SetCellValue(xlsxF.Data, "", "B2", "3", false, "") })
		ops["targeted_docx"] = measure(iters, func() { _, _ = ooxml.ReplaceParagraphText(docxF.Data, 0, "BENCH LAT") })
		ops["targeted_xlsx"] = measure(iters, func() { _, _ = ooxml.SetCellValue(xlsxF.Data, "", "B2", "10", false, "") })
		ops["conflict_check"] = measure(iters, func() { _ = operations.CheckRevision("a", "b") })
		ops["transaction_cycle"] = measure(iters, func() {
			tx := operations.NewTransaction("lat", "d", "op", "b")
			_, _ = tx.Commit("a")
			_, _ = tx.Rollback()
		})
		ops["error"] = nil
		ops["peak_rss_kb"] = sysRSSkb()
		ops["peak_rss_kb_note"] = rssNote
		return ops
	})

	// Suite 7: security negatives via a subprocess.
	suites["security_negative"] = guarded(func() map[string]any {
		base := map[string]any{"peak_rss_kb": nil, "peak_rss_kb_note": rssNote}
		root := repoRoot()
		if root == "" {
			base["security_negative_pass_rate"] = nil
			base["reason"] = "repo root (go.mod) not found"
			base["error"] = nil
			base["peak_rss_kb"] = sysRSSkb()
			return base
		}
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
		defer cancel()
		cmd := exec.CommandContext(ctx, "go", "test", "-run", "TestFS|TestEdit.*Error|TestDecode|TestPlugin", "-count=1", "./internal/...")
		cmd.Dir = root
		var out bytes.Buffer
		cmd.Stdout = &out
		cmd.Stderr = &out
		runErr := cmd.Run()
		passed, failed := 0, 0
		var failedPkgs, failedTests []string
		for _, line := range strings.Split(out.String(), "\n") {
			f := strings.Fields(line)
			if len(f) < 2 {
				continue
			}
			switch f[0] {
			case "ok":
				passed++
			case "FAIL":
				failed++
				failedPkgs = append(failedPkgs, f[1])
			case "---":
				if len(f) >= 3 && f[1] == "FAIL:" {
					failedTests = append(failedTests, f[2])
				}
			}
		}
		base["passed_packages"] = passed
		base["failed_packages"] = failed
		base["failed_package_names"] = failedPkgs
		base["failed_test_names"] = failedTests
		base["samples"] = passed + failed
		base["go_test_error"] = nil
		if runErr != nil && ctx.Err() == context.DeadlineExceeded {
			base["security_negative_pass_rate"] = nil
			base["reason"] = "go test subprocess timed out"
			base["peak_rss_kb"] = sysRSSkb()
			return base
		}
		if passed+failed == 0 {
			base["security_negative_pass_rate"] = nil
			base["reason"] = "no package results parsed: " + runErrString(runErr)
			base["peak_rss_kb"] = sysRSSkb()
			return base
		}
		base["security_negative_pass_rate"] = float64(passed) / float64(passed+failed)
		base["reason"] = nil
		if runErr != nil {
			base["go_test_error"] = runErr.Error()
		}
		base["error"] = nil
		base["peak_rss_kb"] = sysRSSkb()
		return base
	})

	suites["crash"] = map[string]any{
		"error": nil, "panics": panicsObserved, "panic_count": panicsObserved,
		"samples": len(suites), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote,
	}
	suites["timeout"] = map[string]any{
		"error": nil, "timeouts": timeoutsObserved, "timeout_count": timeoutsObserved,
		"samples": len(suites), "peak_rss_kb": sysRSSkb(), "peak_rss_kb_note": rssNote,
	}

	corpusJSON := make([]any, 0, len(manifest))
	for _, m := range manifest {
		corpusJSON = append(corpusJSON, m)
	}
	result := map[string]any{
		"commit": commit, "date": now.Format(time.RFC3339),
		"os": runtime.GOOS, "arch": runtime.GOARCH,
		"cpu_model": cpuModel, "total_ram": totalRAM,
		"go_version":         goVer,
		"python_version":     nullable(pyVer, pyErr),
		"onlyoffice_version": nullable(ooVer, ooErr),
		"builder_version":    nullable(bldVer, bldErr),
		"corpus":             map[string]any{"fixtures": corpusJSON, "samples": len(manifest), "manifest_verified": manifestOK},
		"suites":             suites,
		"notes": []string{
			"visual preservation, perceptual similarity, real office open, and desktop editor task success are NOT measured",
			"results are machine-specific and only comparable on identical hardware and software",
		},
	}

	// Human-readable summary.
	fmt.Printf("bench commit=%s date=%s os=%s/%s\n", commit, now.Format(time.RFC3339), runtime.GOOS, runtime.GOARCH)
	fmt.Printf("cpu=%s ram=%s go=%s\n", cpuModel, totalRAM, goVer)
	fmt.Printf("python=%s onlyoffice=%s builder=%s\n", disp(pyVer, pyErr), disp(ooVer, ooErr), disp(bldVer, bldErr))
	for _, name := range []string{"validation", "noop_preservation", "targeted_change", "conflict_detection", "rollback", "latency", "security_negative", "crash", "timeout"} {
		b, _ := json.Marshal(suites[name])
		fmt.Printf("%s: %s\n", name, string(b))
	}

	if !wantJSON {
		return "", nil
	}
	data, err := json.MarshalIndent(result, "", "  ")
	if err != nil {
		return "", err
	}
	safeCommit := strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' {
			return r
		}
		return '_'
	}, commit)
	stamp := now.Format("20060102T150405Z")
	path := filepath.Join(outDir, fmt.Sprintf("bench-%s-%s.json", safeCommit, stamp))
	for i := 1; ; i++ {
		f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
		if err == nil {
			_, werr := f.Write(data)
			cerr := f.Close()
			if werr != nil {
				return "", werr
			}
			if cerr != nil {
				return "", cerr
			}
			break
		}
		if !os.IsExist(err) {
			return "", err
		}
		path = filepath.Join(outDir, fmt.Sprintf("bench-%s-%s-%d.json", safeCommit, stamp, i))
	}
	if err := json.Unmarshal(data, &map[string]any{}); err != nil {
		return "", err
	}
	return path, nil
}

func fFilename(f fixture) string { return f.Filename }

func nullable(s string, err error) any {
	if err != nil || strings.TrimSpace(s) == "" {
		return nil
	}
	return s
}

func disp(s string, err error) string {
	if err != nil || strings.TrimSpace(s) == "" {
		return "null"
	}
	if len(s) > 80 {
		return s[:80]
	}
	return s
}

func runErrString(err error) string {
	if err == nil {
		return ""
	}
	return err.Error()
}
